/**
 * Get available volumes / sub-branches for a subject and grade
 */
export function getAvailableVolumesForSubjectGrade(
  subject: string,
  grade: string
): string[] {
  const cleanSubject = (subject || '').trim();
  const cleanGrade = (grade || '').trim();
  const mappedSubj = standardSubjectMap[cleanSubject] || cleanSubject;

  // Special handling for Mầm non: Return ALL 10 lessons for the grade
  if (['Nhà trẻ (24-36 tháng)', 'Mẫu giáo bé (3-4 tuổi)', 'Mẫu giáo nhỡ (4-5 tuổi)', 'Mẫu giáo lớn (5-6 tuổi)'].includes(cleanGrade)) {
    const allPreschoolSubjects = [
      'Lĩnh vực Phát triển thể chất',
      'Lĩnh vực Phát triển tình cảm - xã hội',
      'Lĩnh vực Phát triển ngôn ngữ',
      'Lĩnh vực Phát triển nhận thức',
      'Lĩnh vực Phát triển nghệ thuật'
    ];
    let allLessons: string[] = [];
    allPreschoolSubjects.forEach(subj => {
      const key = `${subj}_${cleanGrade}`;
      if (VERIFIED_KNTT_CURRICULUM[key]) {
        allLessons.push(...VERIFIED_KNTT_CURRICULUM[key].lessons.map(l => `[${subj.replace('Lĩnh vực Phát triển ', '')}] ${l}`));
      }
    });
    return ['Chương trình Mầm non'];
  }


  const volumes: string[] = [];
  const keys = Object.keys(VERIFIED_KNTT_CURRICULUM);

  const prefix = `${mappedSubj}_${cleanGrade}_`;
  for (const k of keys) {
    if (k.startsWith(prefix)) {
      const vol = k.replace(prefix, '').trim();
      if (vol && !volumes.includes(vol)) {
        volumes.push(vol);
      }
    }
  }

  // Custom sort volumes: Tập 1 -> Tập 2 -> Sinh hoạt dưới cờ -> Sinh hoạt lớp -> HĐGD theo chủ đề -> Định hướng -> Chuyên đề
  volumes.sort((a, b) => {
    if (a.includes('Tập 1')) return -1;
    if (b.includes('Tập 1')) return 1;
    if (a.includes('Tập 2')) return -1;
    if (b.includes('Tập 2')) return 1;
    if (a.includes('Sinh hoạt dưới cờ') || a.includes('Chào cờ')) return -1;
    if (b.includes('Sinh hoạt dưới cờ') || b.includes('Chào cờ')) return 1;
    if (a.includes('Sinh hoạt lớp') || a.includes('Sinh hoạt')) return -1;
    if (b.includes('Sinh hoạt lớp') || b.includes('Sinh hoạt')) return 1;
    if (a.includes('chủ đề') || a.includes('Chủ đề')) return -1;
    if (b.includes('chủ đề') || b.includes('Chủ đề')) return 1;
    if (a.includes('Chuyên đề')) return 1;
    if (b.includes('Chuyên đề')) return -1;
    return a.localeCompare(b);
  });

  if (volumes.length > 0) {
    const isHDTN = mappedSubj.includes('Hoạt động trải nghiệm') || mappedSubj.includes('HĐTN');
    const defaultLabel = isHDTN ? 'Tất cả các phân môn (Cả năm)' : 'Tất cả các tập (Cả năm)';
    return [defaultLabel, ...volumes];
  }
  return [];
}

/**
 * Intelligent Lesson Extractor / Verifier
 * Matches by exact subject, grade, and volume
 */
export function getVerifiedLessons(
  subject: string,
  grade: string,
  volume?: string
): { themes?: string[]; lessons: string[] } | null {
  // Normalize strings
  const cleanSubject = (subject || '').trim();
  const cleanGrade = (grade || '').trim();
  const cleanVol = (volume || '').trim();
  const mappedSubj = standardSubjectMap[cleanSubject] || cleanSubject;

  // 1. Try exact match with specific volume
  if (
    cleanVol &&
    cleanVol !== 'Cả năm / Không phân tập' &&
    cleanVol !== 'Tất cả các tập' &&
    cleanVol !== 'Tất cả các tập (Cả năm)' &&
    cleanVol !== 'Tất cả các phân môn (Cả năm)' &&
    cleanVol !== 'Cả năm'
  ) {
    // Check direct match
    const directKey = `${mappedSubj}_${cleanGrade}_${cleanVol}`;
    if (VERIFIED_KNTT_CURRICULUM[directKey]) {
      return VERIFIED_KNTT_CURRICULUM[directKey];
    }

    // Fuzzy volume normalization
    let resolvedVol = cleanVol;
    if (cleanVol.includes('Chào cờ') || cleanVol.includes('Sinh hoạt dưới cờ') || cleanVol.toLowerCase().includes('dưới cờ')) {
      resolvedVol = 'Sinh hoạt dưới cờ (Chào cờ)';
    } else if (cleanVol.includes('Sinh hoạt lớp') || (cleanVol.includes('Sinh hoạt') && !cleanVol.includes('dưới cờ')) || cleanVol.toLowerCase().includes('lớp')) {
      resolvedVol = 'Sinh hoạt lớp (Sinh hoạt)';
    } else if (cleanVol.toLowerCase().includes('chủ đề') || cleanVol.toLowerCase().includes('chu de')) {
      resolvedVol = 'Hoạt động giáo dục theo chủ đề';
    } else if (cleanVol.includes('Tin học ứng dụng') || cleanVol.includes('Ứng dụng') || cleanVol.includes('ICT')) {
      resolvedVol = 'Định hướng Tin học ứng dụng';
    } else if (cleanVol.includes('Khoa học máy tính') || cleanVol.includes('Máy tính') || cleanVol.includes('CS')) {
      resolvedVol = 'Định hướng Khoa học máy tính';
    } else if (cleanVol.toLowerCase().includes('chuyên đề') || cleanVol.toLowerCase().includes('chuyen de')) {
      resolvedVol = 'Chuyên đề học tập';
    } else if (cleanVol.includes('Tập 1') || cleanVol === '1' || cleanVol === 'T1') {
      resolvedVol = 'Tập 1';
    } else if (cleanVol.includes('Tập 2') || cleanVol === '2' || cleanVol === 'T2') {
      resolvedVol = 'Tập 2';
    }

    const volKey = `${mappedSubj}_${cleanGrade}_${resolvedVol}`;
    if (VERIFIED_KNTT_CURRICULUM[volKey]) {
      return VERIFIED_KNTT_CURRICULUM[volKey];
    }
  }

  // 2. Try match full grade (e.g. "Toán học_Lớp 8", "Tin học_Lớp 8", "Hoạt động trải nghiệm, hướng nghiệp (HĐTN-HN)_Lớp 9")
  const basicKey = `${mappedSubj}_${cleanGrade}`;
  if (VERIFIED_KNTT_CURRICULUM[basicKey]) {
    return VERIFIED_KNTT_CURRICULUM[basicKey];
  }

  // 3. If no full-grade single entry, combine all standard volumes (Tập 1 + Tập 2)
  const vol1 = VERIFIED_KNTT_CURRICULUM[`${mappedSubj}_${cleanGrade}_Tập 1`];
  const vol2 = VERIFIED_KNTT_CURRICULUM[`${mappedSubj}_${cleanGrade}_Tập 2`];
  if (vol1 || vol2) {
    return {
      themes: [...(vol1?.themes || []), ...(vol2?.themes || [])],
      lessons: [...(vol1?.lessons || []), ...(vol2?.lessons || [])],
    };
  }

  // 4. Intelligent fuzzy matching for custom preschool grades (Mầm non)
  const lowerGrade = cleanGrade.toLowerCase();
  let fallbackPreschoolGrade = '';
  if (
    lowerGrade.includes('nhà trẻ') ||
    lowerGrade.includes('nhóm trẻ') ||
    lowerGrade.includes('tháng') ||
    lowerGrade.includes('12') ||
    lowerGrade.includes('18') ||
    lowerGrade.includes('24') ||
    lowerGrade.includes('36')
  ) {
    fallbackPreschoolGrade = 'Nhà trẻ (24-36 tháng)';
  } else if (lowerGrade.includes('3-4') || lowerGrade.includes('3 – 4') || lowerGrade.includes('bé') || lowerGrade.includes('mầm')) {
    fallbackPreschoolGrade = 'Mẫu giáo bé (3-4 tuổi)';
  } else if (lowerGrade.includes('4-5') || lowerGrade.includes('4 – 5') || lowerGrade.includes('nhỡ') || lowerGrade.includes('chồi')) {
    fallbackPreschoolGrade = 'Mẫu giáo nhỡ (4-5 tuổi)';
  } else if (lowerGrade.includes('5-6') || lowerGrade.includes('5 – 6') || lowerGrade.includes('lớn') || lowerGrade.includes('lá') || lowerGrade.includes('ghép')) {
    fallbackPreschoolGrade = 'Mẫu giáo lớn (5-6 tuổi)';
  }

  if (fallbackPreschoolGrade) {
    const fallbackKey = `${mappedSubj}_${fallbackPreschoolGrade}`;
    if (VERIFIED_KNTT_CURRICULUM[fallbackKey]) {
      return VERIFIED_KNTT_CURRICULUM[fallbackKey];
    }
  }

  return null;
}
